// Bundles src/lib/rules.js into one script for mySleep Night: node scripts/build-rules.mjs
// (the app's copy is ios/MySleepNight/rules.js; src/lib/rules.test.js fails when it is stale).
import { rolldown } from 'rolldown'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
export const OUT = fileURLToPath(new URL('../../ios/MySleepNight/rules.js', import.meta.url))

export async function bundle() {
  const b = await rolldown({ input: root + 'src/lib/rules.js', logLevel: 'silent' })
  const { output } = await b.generate({ format: 'iife', name: 'MySleepRules', minify: false })
  await b.close()
  return '// Generated by frontend/scripts/build-rules.mjs from frontend/src/lib/rules.js: do not edit.\n' + output[0].code
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { writeFileSync } = await import('node:fs')
  writeFileSync(OUT, await bundle())
  console.log('wrote', OUT)
}
